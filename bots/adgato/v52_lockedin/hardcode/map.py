_TILE_TO_ENV: tuple[Environment, ...] = (
    Environment.EMPTY,
    Environment.WALL,
    Environment.ORE_TITANIUM,
    Environment.ORE_AXIONITE,
)


def decode(data: bytes, n: int) -> list[Environment]:
    tiles: list[Environment] = []
    for b in data:
        for j in range(4):
            if len(tiles) >= n:
                break
            tiles.append(_TILE_TO_ENV[(b >> (j * 2)) & 3])
    return tiles


