# A* pathing algorithm
def get_next_move(
    ct: Controller,
    map_enemy_buildings: list[EntityType | None],
    map_walkable: list[int | float],
    map_env: list[Environment],
    width: int,
    height: int,
    start_idx: int,
    goal_idx: int,
    *,
    diagonal: bool,
    max_depth: int = 0,
    enemy_base_walkable: bool = True,
) -> Direction | None:
    start_t = ct.get_cpu_time_elapsed()

    if start_idx == goal_idx:
        return None

    direction_len = 8 if diagonal else 4

    goal_x, goal_y = goal_idx % width, goal_idx // width

    # Use a list for g_score (initialized to a large integer)
    # This is significantly faster than a dictionary.
    inf = 999999
    g_scores = [inf] * (width * height)
    g_scores[start_idx] = 0

    open_set: list[tuple[float, int, int, Direction]] = []

    # Track the best move found so far based on heuristic distance
    sdx = abs(start_idx % width - goal_x)
    sdy = abs(start_idx // width - goal_y)
    best_h: float
    best_h = sdx + sdy + (1.414 - 2) * min(sdx, sdy) if diagonal else sdx + sdy
    best_move = None

    # Initial neighbors to "lock in" the first_move direction
    sx, sy = start_idx % width, start_idx // width
    for di in range(direction_len):
        direction = DIRECTIONS[di]
        dx, dy = direction.delta()
        nx, ny = sx + dx, sy + dy
        if 0 <= nx < width and 0 <= ny < height:
            neighbor = ny * width + nx
            if (
                map_walkable[neighbor] < BAD_WALKABLE
                and map_env[neighbor] != Environment.WALL
                and (
                    enemy_base_walkable
                    or map_enemy_buildings[neighbor] != EntityType.CORE
                )
            ):
                sdx = abs(nx - goal_x)
                sdy = abs(ny - goal_y)
                h: float
                h = sdx + sdy + (1.414 - 2) * min(sdx, sdy) if diagonal else sdx + sdy
                h *= map_walkable[neighbor]

                g_scores[neighbor] = 1
                heapq.heappush(open_set, (1 + h, 1, neighbor, direction))
                if h < best_h:
                    best_h = h
                    best_move = direction

    while open_set:
        _f, depth, current, first_move = heapq.heappop(open_set)

        if current == goal_idx:
            return first_move

        # Depth limit check
        if max_depth > 0 and depth >= max_depth:
            continue

        cx, cy = current % width, current // width

        for di in range(direction_len):
            # Budget of 3ms, if we exceed, then just submit whatever move
            if ct.get_cpu_time_elapsed() - start_t > 3000:
                return best_move

            direction = DIRECTIONS[di]
            dx, dy = direction.delta()
            nx, ny = cx + dx, cy + dy

            if 0 <= nx < width and 0 <= ny < height:
                neighbor = ny * width + nx

                if (
                    map_walkable[neighbor] < BAD_WALKABLE
                    and map_env[neighbor] != Environment.WALL
                    and (
                        enemy_base_walkable
                        or map_enemy_buildings[neighbor] != EntityType.CORE
                    )
                ):
                    new_g = depth + 1
                    if new_g < g_scores[neighbor]:
                        g_scores[neighbor] = new_g
                        sdx = abs(nx - goal_x)
                        sdy = abs(ny - goal_y)
                        h: float
                        if diagonal:
                            h = (sdx + sdy) + (1.414 - 2) * min(sdx, sdy)
                        else:
                            h = sdx + sdy
                        h *= map_walkable[neighbor]

                        # Update best-effort if we found a tile closer to the goal
                        if h < best_h:
                            best_h = h
                            best_move = first_move

                        heapq.heappush(
                            open_set,
                            (new_g + h, new_g, neighbor, first_move),
                        )

    return best_move


class Core:
    """Controller for core building"""

    def __init__(self, _ct: Controller) -> None:
        self.num_spawned = 0
        self.cooldown = 10

    def run(self, ct: Controller) -> None:
        """Exectues once each round"""
        spawn_pos = ct.get_position()

        # Need to tweak these values, balance of early game econ -> constant pressure on enemy base
        if (
            self.num_spawned < 20
            and ct.get_global_resources()[0] > 500
            and ct.can_spawn(spawn_pos)
        ):
            ct.spawn_builder(spawn_pos)
            self.num_spawned += 1
        elif ct.get_global_resources()[0] > 150 and self.cooldown <= 0:
            if ct.can_spawn(spawn_pos):
                ct.spawn_builder(spawn_pos)

                self.num_spawned += 1
                self.cooldown = 15
        else:
            self.cooldown -= 1


