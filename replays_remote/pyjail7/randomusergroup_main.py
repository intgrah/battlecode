    def __init__(self, ct: Controller) -> None:
        pass

    def run(self, ct: Controller) -> None:
        """Exectues once each round"""
        direction = ct.get_direction(ct.get_id())

        pos = ct.get_position().add(direction)
        if ct.can_fire(pos):
            ct.fire(pos)
            return

        pos = pos.add(direction)
        if ct.can_fire(pos):
            ct.fire(pos)
            return

        pos = pos.add(direction)
        if ct.can_fire(pos):
            ct.fire(pos)
            return


